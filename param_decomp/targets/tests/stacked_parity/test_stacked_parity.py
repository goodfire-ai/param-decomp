"""The fixtures predate the recon-loss-terms unification; their metric keys are the
old fixed names. The stored arrays themselves are untouched — only the lookup into
the live metrics dict is remapped."""


def _load() -> tuple[dict[str, np.ndarray], GLUDecomposedModel, ComponentStacks, jnp.ndarray]:
    assert FIXTURES.exists(), "regenerate via gen_stacked_fixtures.py on the base branch"
    f = dict(np.load(FIXTURES))
    cfg = tiny_glu_cfg()
    first = int(f["_scalar_FIRST_LAYER"])
    last = int(f["_scalar_LAST_LAYER"])
    C = int(f["_scalar_C"])

    def a(key: str) -> jnp.ndarray:
        return jnp.asarray(f[key])

    layers = [
        GLULayer(
            ln1=a(f"tgt::layers.{i}.ln1"),
            ln2=a(f"tgt::layers.{i}.ln2"),
            attn=FrozenAttn(
                a(f"tgt::layers.{i}.wq"),
                a(f"tgt::layers.{i}.wk"),
                a(f"tgt::layers.{i}.wv"),
                a(f"tgt::layers.{i}.wo"),
                cfg.n_head,
                cfg.n_kv_head,
                cfg.head_dim,
                cfg.n_rep,
                "auto",
            ),  # fmt: skip
            mlp=GatedMLP(
                Wg=a(f"tgt::layers.{i}.Wg"),
                Wu=a(f"tgt::layers.{i}.Wu"),
                Wd=a(f"tgt::layers.{i}.Wd"),
            ),
        )
        for i in range(first, cfg.n_layer)
    ]
    sites = glu_site_specs(cfg, mlp_family_site_cs(first, last, C))
    model = build_decomposed_lm(
        embed=jnp.zeros((cfg.vocab_size, cfg.n_embd), jnp.float32),
        layers=layers,
        norm=a("tgt::norm"),
        lm_head=a("tgt::lm_head"),
        inv_freq=llama3_inv_freq(cfg),
        cfg=cfg,
        sites=sites,
    )
    vu = component_stacks_from_sites(
        {s.name: (a(f"vu::V::{s.name}"), a(f"vu::U::{s.name}")) for s in sites}
    )
    return f, model, vu, a("resid")


def _assert_close(got: jnp.ndarray, want: np.ndarray, what: str) -> None:
    np.testing.assert_allclose(np.asarray(got), want, rtol=RTOL, atol=ATOL, err_msg=what)


def _build_trajectory_ci_fn(model: DecomposedModel, key: jnp.ndarray):
    """The new chunkwise CI fn (one chunk over all sites, reading the residual entering the
    first decomposed block) — the migrated replacement for the old per-site `CIArch`."""
    from param_decomp.core.ci_fn import (
        Chunk,
        ChunkwiseTransformerCIArch,
        MHACIAttention,
        build_ci_fn,
    )

    first_block = min(int(n.split(".")[1]) for n in model.site_names)
    arch = ChunkwiseTransformerCIArch(
        chunks=(Chunk(input_taps=(f"resid.{first_block}",), output_sites=model.site_names),),
        input_dim=tiny_glu_cfg().n_embd,
        d_model=16,
        n_blocks=2,
        attention=MHACIAttention(n_heads=2),
        ffn_hidden=32,
        ffn_kind="gelu",
        learned_norm_scale=False,
    )
    return build_ci_fn(arch, model.sites, key)


@_PENDING_REGEN
def test_clean_output_matches():
    f, model, _vu, resid = _load()
    clean = run_clean(model, resid)
    _assert_close(clean, f["out::clean"], "clean logits")


@_PENDING_REGEN
def test_site_inputs_and_weight_deltas_match():
    f, model, vu, resid = _load()

    def site_input_key(site: str) -> str:
        layer, kind = parse_site_name(site)
        match kind:
            case "q" | "k" | "v":
                return attention_input_tap_key(layer)
            case "o":
                return attention_output_tap_key(layer)
            case "gate" | "up":
                return mlp_input_tap_key(layer)
            case "down":
                return mlp_hidden_tap_key(layer)
            case _:
                raise AssertionError(kind)

    input_keys = tuple(site_input_key(site) for site in model.site_names)
    captures = capture_clean(model, resid, tuple(dict.fromkeys(input_keys)))
    for name, input_key in zip(model.site_names, input_keys, strict=True):
        _assert_close(captures[input_key], f[f"out::site_input::{name}"], f"site_input {name}")
    deltas = model.weight_deltas(vu)
    for name in model.site_names:
        _assert_close(
            site_weight_delta(deltas, vu, name), f[f"out::wd::{name}"], f"weight_delta {name}"
        )


@_PENDING_REGEN
def test_masked_output_match():
    f, model, vu, resid = _load()
    masks = {s: jnp.asarray(f[f"mask::{s}"]) for s in model.site_names}
    delta_masks = {s: jnp.asarray(f[f"delta_mask::{s}"]) for s in model.site_names}
    prepared_weights = model.prepare_compute_weights(vu, None)
    masked_all = run_masked(
        model,
        prepared_weights,
        resid,
        masks,
        delta_masks,
        None,
        True,
        remat=False,
    )
    _assert_close(masked_all, f["out::masked_all"], "masked_output (all live)")


@pytest.mark.xfail(
    reason="needs torch-oracle golden regen: CI numerics changed. The CI fn moved from the "
    "old per-site-concat `CIArch` to the chunkwise transformer reading RESIDUAL taps "
    "(`ChunkwiseTransformerCIFn`), so every CI-dependent trajectory golden (`out::step*`, "
    "`out::final_{V,U,src}`) is stale. Regen is torch-oracle-dependent (the `torch-oracle` "
    "git tag in a torch venv), out of scope for the API migration. The CI-INDEPENDENT "
    "forward pins (clean / site_input / weight_delta / masked) still verify in the other "
    "tests. The body below is migrated to the new chunkwise CI fn so it runs (and fails on "
    "the stale numerics) rather than erroring.",
    strict=True,
)
def test_train_trajectory_matches():
    f, model, vu, resid = _load()
    T = int(f["_scalar_T"])
    n_train_steps = int(f["_scalar_N_TRAIN_STEPS"])
    n_warmup = int(f["_scalar_N_WARMUP"])

    ci_fn = _build_trajectory_ci_fn(model, random.PRNGKey(2))
    sources = init_persistent_sources(
        model.site_names, tuple(s.C for s in model.sites), (1, T), jnp.float32, random.PRNGKey(3)
    )
    for name, source in sources.items():
        np.testing.assert_array_equal(np.asarray(source), f[f"src::{name}"])

    opt_vu = optax.chain(optax.clip_by_global_norm(0.01), optax.adamw(1e-3, weight_decay=0.0))
    opt_ci = optax.adamw(1e-3, weight_decay=0.0)
    ppgd_cfg = PersistentPGDReconLossConfig(
        coeff=0.5,
        source_shape="sc",
        optimizer=AdamPGDConfig(
            beta1=0.5,
            beta2=0.99,
            lr_schedule=ScheduleConfig(
                max_val=0.01,
                points=(Knot(at=0.0, frac=0.0), Knot(at=0.025, frac=1.0), Knot(at=1.0, frac=1.0)),
            ),
        ),
        n_warmup_steps=n_warmup,
    )
    assert ppgd_cfg.coeff is not None
    state = TrainState(
        decomposition=Decomposition(components=vu, ci_fn=ci_fn),
        training=TrainingItem(
            components_opt_state=opt_vu.init(eqx.filter(vu, eqx.is_array)),
            ci_fn_opt_state=opt_ci.init(eqx.filter(ci_fn, eqx.is_array)),
            adversaries={
                ppgd_cfg.type: PersistentAdversary(
                    sources=sources,
                    opt_state=init_sources_adam_state(sources),
                    state_key=ppgd_cfg.type,
                    adam=ppgd_cfg.optimizer,
                    n_warmup=ppgd_cfg.n_warmup_steps,
                )
            },
            freq_ema=None,
            step=jnp.zeros((), jnp.int32),
        ),
    )
    loss_terms = build_objective(
        (
            FaithfulnessLossConfig(coeff=1e5),
            ImportanceMinimalityLossConfig(
                coeff=5e-6,
                pnorm=ScheduleConfig(
                    max_val=2.0, points=(Knot(at=0.0, frac=1.0), Knot(at=1.0, frac=0.2))
                ),
                frequency=FrequencyMinimalityConfig(coeff=1e-6, reference_datapoint_count=32),
            ),
            StochasticReconSubsetLossConfig(
                routing=UniformKSubsetRoutingConfig(),
                coeff=0.5,
                n_mask_samples=1,
            ),
            ppgd_cfg,
        ),
        model.site_names,
    )
    placed = PlacedModel(model=model, placement=None)
    step_fn = make_train_step(
        model_static=placed,
        substrate=ForwardSubstrate.of(
            placed,
            remat_recon_forwards=False,
            remat_ci_fn=False,
            ci_capture_keys=ci_fn.capture_keys,
            ci_placement=None,
        ),
        objective=loss_terms,
        components_optimizer=opt_vu,
        ci_fn_optimizer=opt_ci,
        total_steps=100,
        faithfulness=faithfulness_loss_for(model),
    )
    run_key = random.PRNGKey(7)
    for step_idx in range(n_train_steps):
        state, metrics = step_fn(placed, state, resid, random.fold_in(run_key, step_idx))
        for fixture_key in STABLE_FIXTURE_METRIC_KEYS:
            metric_key = METRIC_KEY_BY_FIXTURE_KEY.get(fixture_key, fixture_key)
            got = float(metrics[metric_key])
            want = float(f[f"out::step{step_idx}::{fixture_key}"])
            assert abs(got - want) <= ATOL + RTOL * abs(want), (
                f"step{step_idx} {fixture_key}: per-site {got!r} vs stacked {want!r}"
            )

    assert isinstance(state.decomposition.components, ComponentStacks)
    for name in model.site_names:
        site_components = state.decomposition.components.site(name)
        _assert_close(site_components.V, f[f"out::final_V::{name}"], f"final V {name}")
        _assert_close(site_components.U, f[f"out::final_U::{name}"], f"final U {name}")
    final_sources = state.training.adversaries["PersistentPGDReconLoss"].sources
    for name in model.site_names:
        packed_source = jnp.concatenate(
            [final_sources[name].components, final_sources[name].delta[..., None]], axis=-1
        )
        _assert_close(packed_source, f[f"out::final_src::{name}"], f"final src {name}")
